import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import ts from 'typescript';
const source=await fs.readFile('src/lib/multi-file-import.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {readImportFiles}=await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const a={name:'class-5.xlsx',size:10,lastModified:1},b={name:'class-6.xls',size:20,lastModified:2},c={name:'class-7.csv',size:30,lastModified:3};
const progress=[]; let active=0,peak=0;
const data=new Map([[a,[{id:1},{id:2}]],[b,[{id:2},{id:3}]],[c,[{id:4}]]]);
const result=await readImportFiles([a,b,c],async file=>{active++;peak=Math.max(peak,active);await new Promise(resolve=>setTimeout(resolve,1));active--;return data.get(file);},p=>progress.push(p));
assert.equal(peak,1,'workbooks are parsed sequentially');
assert.deepEqual(result.rows.map(r=>r.id),[1,2,2,3,4],'combined rows reach module validation without silently dropping duplicates');
assert.deepEqual(result.sources,[{file:a.name,row:2,fileIndex:0},{file:a.name,row:3,fileIndex:0},{file:b.name,row:2,fileIndex:1},{file:b.name,row:3,fileIndex:1},{file:c.name,row:2,fileIndex:2}]);
assert.deepEqual(result.summaries.map(f=>f.rows),[2,2,1]);assert.equal(progress.length,3);
await assert.rejects(()=>readImportFiles([],async()=>[]),/at least one/);
await assert.rejects(()=>readImportFiles([a,b],async file=>{if(file===b)throw Error('Broken workbook');return data.get(file);}),/class-6.xls: Broken workbook/);
await assert.rejects(()=>readImportFiles([a,b],async file=>file===b?[]:data.get(file)),/class-6.xls: No data rows/);
await assert.rejects(()=>readImportFiles([a,a],async file=>data.get(file)),/selected twice/);
await assert.rejects(()=>readImportFiles([{...a,name:'picture.png'}],async()=>[]),/Choose an/);
const large=await readImportFiles([a,b],async file=>Array.from({length:1200},(_,id)=>({id,file:file.name})));
assert.equal(large.rows.length,2400);assert.equal(large.sources[1200].row,2);
console.log('PASS: mixed workbook selection, sequential parsing, combined validation input, file/row provenance, errors, empty files, duplicate selection and 2400-row import');
